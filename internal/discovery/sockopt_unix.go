//go:build !windows

package discovery

import "syscall"

// reuseAddr lets perekat share the discovery port with another KDE Connect
// implementation running on the same machine.
func reuseAddr(_, _ string, c syscall.RawConn) error {
	var serr error
	err := c.Control(func(fd uintptr) {
		serr = syscall.SetsockoptInt(int(fd), syscall.SOL_SOCKET, syscall.SO_REUSEADDR, 1)
	})
	if err != nil {
		return err
	}
	return serr
}
